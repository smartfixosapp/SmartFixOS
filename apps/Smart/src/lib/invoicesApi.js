async function logoDataUrl(url) {
  if (!url) return null;
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 5000);
  try {
    const res = await fetch(url, { mode: "cors", signal: ctrl.signal });
    if (!res.ok) return null;
    const blob = await res.blob();
    return await new Promise((resolve) => {
      const r = new FileReader();
      r.onload = () => {
        const img = new Image();
        img.onload = () => resolve({ dataUrl: r.result, w: img.naturalWidth, h: img.naturalHeight });
        img.onerror = () => resolve(null);
        img.src = r.result;
      };
      r.onerror = () => resolve(null);
      r.readAsDataURL(blob);
    });
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

const BLUE = [46, 97, 242];
const WIN_ANSI_EXTRA = new Set([8364, 8218, 402, 8222, 8230, 8224, 8225, 710, 8240, 352, 8249, 338, 381, 8216, 8217, 8220, 8221, 8226, 8211, 8212, 732, 8482, 353, 8250, 339, 382, 376]);
const pdfSafe = (s) => {
  const base = String(s ?? "").replace(/→/g, "->").replace(/–/g, "-").replace(/—/g, "-").replace(/×/g, "x");
  let out = "";
  for (const ch of base) {
    const c = ch.codePointAt(0);
    if (c < 256 || WIN_ANSI_EXTRA.has(c)) { out += ch; continue; }
    const plain = ch.normalize("NFKD").replace(/[\u0300-\u036f]/g, "");
    out += /^[\x20-\xff]+$/.test(plain) ? plain : "?";
  }
  return out;
};

export async function buildInvoicePDF({ invoiceNumber, company, orders, subtotal, taxRate, taxAmount, total, notes, tenant, language, terms, issuedAt, dueDate, isVoided }) {
  const { jsPDF } = await import("jspdf");
  const lang = language === "en" ? "en" : "es";
  const s = (k) => pdfSafe(str(k, lang));
  const currency = tenant?.currency || "USD";
  const money = (v) => pdfSafe(fmtMoney(v, currency, lang));
  const doc = new jsPDF({ unit: "pt", format: "letter" });
  const W = 612;
  const H = 792;
  const L = 40;
  const R = W - 40;
  const logo = await logoDataUrl(tenant?.logo_url);
  const text = (t, x, y, { size = 10, style = "normal", color = [0, 0, 0], align, font = "helvetica" } = {}) => {
    doc.setFont(font, style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
    doc.text(pdfSafe(t), x, y, { baseline: "top", align });
  };
  const truncate = (t, maxW, size, style = "normal") => {
    doc.setFont("helvetica", style);
    doc.setFontSize(size);
    let out = pdfSafe(t);
    if (doc.getTextWidth(out) <= maxW) return out;
    while (out.length > 1 && doc.getTextWidth(`${out}...`) > maxW) out = out.slice(0, -1);
    return `${out}...`;
  };
  const DARK = [85, 85, 85];
  let y = 40;
  if (logo) {
    const scale = Math.min(50 / Math.max(logo.h, 1), 170 / Math.max(logo.w, 1));
    try { doc.addImage(logo.dataUrl, "PNG", L, y, logo.w * scale, logo.h * scale); y += logo.h * scale + 8; } catch { y += 0; }
  }
  text(tenant?.admin_name || tenant?.name || s("workshopFallback"), L, y, { size: 22, style: "bold" });
  y += 26;
  [tenant?.address, tenant?.admin_phone && `${s("phone")}: ${tenant.admin_phone}`, tenant?.email].filter(Boolean).forEach((line) => { text(line, L, y, { size: 10, color: DARK }); y += 13; });
  const reg = String(tenant?.settings?.merchant_registration || "").trim();
  if (reg) { text(`${s("merchantReg")}: ${reg}`, L, y, { size: 10, color: DARK }); y += 13; }
  y += 4;
  doc.setDrawColor(190, 190, 190);
  doc.setLineWidth(0.6);
  doc.line(L, y, R, y);
  y += 12;
  text(s("invoice"), L, y, { size: 18, style: "bold", color: BLUE });
  text(invoiceNumber, R, y + 2, { size: 14, style: "bold", font: "courier", align: "right" });
  y += 24;
  text(`${s("issued")}: ${fmtDate(issuedAt, lang)}`, L, y, { size: 10, color: DARK });
  let ry = y;
  [`${s("terms")}: ${pdfSafe(termsLabel(terms, lang))}`, dueDate && `${s("due")}: ${fmtDate(dueDate, lang)}`].filter(Boolean).forEach((t) => { text(t, R, ry, { size: 10, style: "bold", color: DARK, align: "right" }); ry += 13; });
  y = Math.max(y + 14, ry) + 14;

  const totalW = W - 80;
  const billW = totalW * 0.62;
  const perW = totalW - billW - 12;
  const billLines = [[companyName(company), 13, "bold", [0, 0, 0]]];
  if (company.company_name && company.name && company.name !== companyName(company)) billLines.push([`${s("contact")}: ${company.name}`, 10.5, "normal", DARK]);
  const cp = [company.phone, company.email].filter(Boolean);
  if (cp.length) billLines.push([cp.join(" · "), 10.5, "normal", DARK]);
  if (String(company.tax_id || "").trim()) billLines.push([`${s("customerTaxId")}: ${String(company.tax_id).trim()}`, 10.5, "normal", DARK]);
  const perLines = [];
  const period = billingPeriod(orders);
  if (period) {
    const sameYear = period.start.getFullYear() === period.end.getFullYear();
    perLines.push([sameYear ? `${fmtShort(period.start, lang)} - ${fmtDate(period.end, lang)}` : `${fmtDate(period.start, lang)} - ${fmtDate(period.end, lang)}`, sameYear ? 13 : 11, "bold", [0, 0, 0]]);
  }
  perLines.push([devicesLabel(orders.length, lang), 10.5, "normal", DARK]);
  const boxH = Math.max(billLines.length * 15 + 26, perLines.length * 15 + 26);
  const box = (x, w, label, lines) => {
    doc.setFillColor(245, 245, 245);
    doc.setDrawColor(190, 190, 190);
    doc.setLineWidth(0.5);
    doc.roundedRect(x, y, w, boxH, 6, 6, "FD");
    let iy = y + 8;
    text(label, x + 12, iy, { size: 9, style: "bold", color: DARK });
    iy += 13;
    lines.forEach(([t, size, style, color]) => { text(truncate(t, w - 24, size, style), x + 12, iy, { size, style, color }); iy += 15; });
  };
  box(L, billW, s("billTo"), billLines);
  box(L + billW + 12, perW, s("period"), perLines);
  y += boxH + 14;

  const tableW = W - 80;
  const rowH = 34;
  const orderX = L + 8;
  const svcX = L + 62;
  const datesX = L + 340;
  const svcMax = datesX - svcX - 10;
  const amtR = L + tableW - 8;
  const headerRow = () => {
    doc.setFillColor(230, 230, 230);
    doc.roundedRect(L, y, tableW, 22, 4, 4, "F");
    const hy = y + 7;
    text(s("colOrder"), orderX, hy, { size: 8, style: "bold", color: DARK });
    text(s("colService"), svcX, hy, { size: 8, style: "bold", color: DARK });
    text(s("colDates"), datesX, hy, { size: 8, style: "bold", color: DARK });
    text(s("colAmount"), amtR, hy, { size: 8, style: "bold", color: DARK, align: "right" });
    y += 22;
  };
  const newPage = () => { doc.addPage(); y = 40; };
  headerRow();
  orders.forEach((o, i) => {
    if (y > H - 200) { newPage(); headerRow(); }
    if (i % 2 === 1) { doc.setFillColor(247, 247, 247); doc.rect(L, y, tableW, rowH, "F"); }
    const top = y + 6;
    const bottom = y + 19;
    text(truncate(o.order_number || o.id || "-", svcX - orderX - 6, 10, "bold"), orderX, top, { size: 10, style: "bold", font: "courier" });
    const device = [o.device_brand, o.device_family, o.device_model].filter(Boolean).join(" ").split(/\s+/).filter((w, idx, arr) => arr.findIndex((x) => x.toLowerCase() === w.toLowerCase()) === idx).join(" ") || "-";
    text(truncate(device, svcMax, 10, "bold"), svcX, top, { size: 10, style: "bold" });
    const desc = serviceDescription(o);
    if (desc) text(truncate(desc, svcMax, 8.5), svcX, bottom, { size: 8.5, color: [90, 90, 90] });
    const rec = receivedDate(o);
    const del = deliveredDate(o);
    text(truncate(`${rec ? fmtShort(rec, lang) : "-"} -> ${del ? fmtShort(del, lang) : "-"}`, 105, 8.5), datesX, top, { size: 8.5, color: [90, 90, 90] });
    text(money(orderSubtotal(o, taxRate)), amtR, top, { size: 10.5, style: "bold", align: "right" });
    y += rowH;
  });
  y += 14;
  if (y + 64 > H - 90) newPage();
  const labelX = R - 220;
  text(`${s("subtotal")}:`, labelX, y, { size: 10, color: DARK });
  text(money(subtotal), R, y, { size: 10, style: "bold", align: "right" });
  y += 16;
  const pct = Math.round(taxRate * 10000) % 10 === 0 ? (taxRate * 100).toFixed(1) : (taxRate * 100).toFixed(2);
  const taxLabel = String(tenant?.tax_label || "").trim() || "IVU";
  text(`${taxLabel} (${pct}%):`, labelX, y, { size: 10, color: DARK });
  text(money(taxAmount), R, y, { size: 10, style: "bold", align: "right" });
  y += 16;
  doc.setDrawColor(190, 190, 190);
  doc.setLineWidth(0.5);
  doc.line(labelX, y + 2, R, y + 2);
  y += 10;
  text(`${s("total")}:`, labelX, y, { size: 14, style: "bold", color: BLUE });
  text(money(total), R, y, { size: 14, style: "bold", color: BLUE, align: "right" });
  y += 22;
  const trimmed = String(notes || "").trim();
  if (trimmed) {
    y += 16;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    const lines = doc.splitTextToSize(pdfSafe(trimmed), W - 80);
    const nh = lines.length * 12;
    if (y + nh + 12 > H - 90) newPage();
    text(s("notes"), L, y, { size: 9, style: "bold", color: DARK });
    doc.setTextColor(0, 0, 0);
    doc.text(lines, L, y + 12, { baseline: "top" });
  }
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p += 1) {
    doc.setPage(p);
    if (isVoided) {
      doc.saveGraphicsState();
      doc.setGState(new doc.GState({ opacity: 0.22 }));
      doc.setFont("helvetica", "bold");
      const fs = 92;
      doc.setFontSize(fs);
      doc.setTextColor(214, 48, 48);
      const word = s("voided");
      const half = doc.getTextWidth(word) / 2;
      const rad = (32 * Math.PI) / 180;
      const lift = 0.36 * fs;
      doc.text(word, W / 2 - half * Math.cos(rad) + lift * Math.sin(rad), H / 2 + half * Math.sin(rad) + lift * Math.cos(rad), { angle: 32 });
      doc.restoreGraphicsState();
    }
  }
  doc.setPage(pages);
  text(s("thanks"), W / 2, H - 60, { size: 11, style: "bold", color: BLUE, align: "center" });
  const now = new Intl.DateTimeFormat("sv-SE", { timeZone: "America/Puerto_Rico", dateStyle: "short", timeStyle: "short" }).format(new Date());
  text(`${s("generatedBy")} · ${now}`, W / 2, H - 30, { size: 8, color: [170, 170, 170], align: "center" });
  return doc.output("blob");
}

