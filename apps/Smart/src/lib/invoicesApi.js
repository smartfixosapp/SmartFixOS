export const recipientEmail = (company) => {
  const billing = String(company?.billing_email || "").trim();
  if (billing) return billing;
  return String(company?.email || "").trim();
};

export const isVoided = (inv) => !!inv?.voided_at;
export function isOverdue(inv) {
  if (isVoided(inv) || !inv?.due_date) return false;
  const due = new Date(`${String(inv.due_date).slice(0, 10)}T00:00:00`);
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  return due < today;
}
