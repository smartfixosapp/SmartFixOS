const locale = (lang) => (lang === "en" ? "en-US" : "es-PR");
export const fmtDate = (d, lang) => new Intl.DateTimeFormat(locale(lang), { day: "numeric", month: "short", year: "numeric" }).format(d).replace(/\./g, "");
export const fmtShort = (d, lang) => new Intl.DateTimeFormat(locale(lang), { day: "numeric", month: "short" }).format(d).replace(/\./g, "");
export const fmtMoney = (v, currency, lang) => new Intl.NumberFormat(locale(lang), { style: "currency", currency: currency || "USD", maximumFractionDigits: 2 }).format(Number(v) || 0);

const NON_BILLABLE = new Set(["cancelled", "not_repairable", "abandoned"]);
export const isBillable = (o) => !NON_BILLABLE.has(String(o.status || "").toLowerCase());
export const orderTotal = (o) => (o.cost_estimate !== null && o.cost_estimate !== undefined && o.cost_estimate !== "" ? num(o.cost_estimate) : num(o.labor_cost));
export const orderSubtotal = (o, rate) => (rate > 0 ? orderTotal(o) / (1 + rate) : orderTotal(o));
export const companyName = (c) => (String(c?.company_name || "").trim() ? c.company_name : c?.name || "Cliente");

export function matches(order, company) {
  if (order.customer_id && company.id && order.customer_id === company.id) return true;
  const oc = String(order.customer_name || "").trim().toLowerCase();
  const cn = String(company.company_name || company.name || "").trim().toLowerCase();
  return !!cn && oc === cn;
}

export function serviceDescription(order) {
  const items = (Array.isArray(order.order_items) ? order.order_items : []).filter((i) => i && i.type !== "discount" && num(i.price) >= 0 && String(i.name || "").trim());
  if (items.length) return items.map((i) => (num(i.quantity) > 1 ? `${i.name} ×${Math.trunc(num(i.quantity))}` : i.name)).join(", ");
  return String(order.initial_problem || "").trim();
}

export const receivedDate = (o) => (o.created_date ? new Date(o.created_date) : null);
export function deliveredDate(o) {
  const hist = Array.isArray(o.status_history) ? o.status_history : [];
  let max = null;
  hist.forEach((e) => { if (e?.status === "delivered" && e.timestamp) { const t = new Date(e.timestamp); if (!Number.isNaN(t.getTime()) && (!max || t > max)) max = t; } });
  return max;
}

export function billingPeriod(orders) {
  const starts = orders.map(receivedDate).filter(Boolean);
  if (!starts.length) return null;
  const first = new Date(Math.min(...starts.map((d) => d.getTime())));
  const ends = orders.map((o) => deliveredDate(o) || receivedDate(o)).filter(Boolean);
  const last = ends.length ? new Date(Math.max(...ends.map((d) => d.getTime()))) : first;
  return { start: first, end: last };
}

const dayStr = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;

async function fetchAllOrders(tenantId) {
  const out = [];
  for (let off = 0; off < 10000; off += 1000) {
    const { data, error } = await supabase.from("order").select("*").eq("tenant_id", tenantId).eq("is_deleted", false).order("created_at", { ascending: false }).range(off, off + 999);
    if (error) throw error;
    out.push(...(data || []));
    if (!data || data.length < 1000) break;
  }
  return out;
}

export async function loadCompanies(tenantId) {
  const [{ data: companies, error }, orders] = await Promise.all([
    supabase.from("customer").select("*").eq("tenant_id", tenantId).eq("is_b2b", true).limit(1000),
    fetchAllOrders(tenantId),
  ]);
  if (error) throw error;
  return (companies || []).filter((c) => orders.some((o) => matches(o, c) && isBillable(o) && orderTotal(o) > 0))
    .sort((a, b) => companyName(a).localeCompare(companyName(b), undefined, { sensitivity: "base" }));
}

