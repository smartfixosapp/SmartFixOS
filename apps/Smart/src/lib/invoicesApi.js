export async function regenerateInvoicePDF({ invoice, tenant, isVoided: stamped }) {
  const ids = Array.isArray(invoice.order_ids) ? invoice.order_ids : [];
  if (!ids.length) throw new Error("La factura no tiene órdenes");
  const [ordersRes, custRes] = await Promise.all([
    supabase.from("order").select("*").in("id", ids),
    invoice.customer_id ? supabase.from("customer").select("*").eq("id", invoice.customer_id).limit(1) : Promise.resolve({ data: [], error: null }),
  ]);
  if (ordersRes.error) throw ordersRes.error;
  if (custRes.error) throw custRes.error;
  const rows = ordersRes.data || [];
  if (rows.length < ids.length) throw new Error("No se pudieron leer todas las órdenes de la factura");
  const company = custRes.data?.[0] || { name: invoice.customer_name || "Cliente", company_name: invoice.customer_name, tax_id: invoice.customer_tax_id };
  const order = new Map(rows.map((o) => [o.id, o]));
  return buildInvoicePDF({
    invoiceNumber: invoice.invoice_number, company, orders: ids.map((id) => order.get(id)).filter(Boolean), subtotal: num(invoice.subtotal), taxRate: num(invoice.tax_rate), taxAmount: num(invoice.tax_amount), total: num(invoice.total),
    notes: invoice.notes || "", tenant, language: invoice.language === "en" ? "en" : "es", terms: invoice.payment_terms || "due_on_receipt",
    issuedAt: invoice.created_at ? new Date(invoice.created_at) : new Date(), dueDate: invoice.due_date ? new Date(`${String(invoice.due_date).slice(0, 10)}T12:00:00`) : null, isVoided: stamped,
  });
}

export const regenerateVoidedPDF = ({ invoice, tenant }) => regenerateInvoicePDF({ invoice, tenant, isVoided: true });

export function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10000);
}

