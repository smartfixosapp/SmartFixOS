export async function loadInvoiceableOrders(tenantId, company) {
  const [orders, invRes] = await Promise.all([
    fetchAllOrders(tenantId),
    supabase.from("invoice").select("order_ids").eq("tenant_id", tenantId).eq("customer_id", company.id).is("voided_at", null).limit(2000),
  ]);
  if (invRes.error) throw invRes.error;
  const done = new Set((invRes.data || []).flatMap((i) => (Array.isArray(i.order_ids) ? i.order_ids : [])));
  return orders.filter((o) => o.id && !done.has(o.id) && matches(o, company) && isBillable(o) && orderTotal(o) > 0);
}

export async function createInvoice({ tenantId, company, orders, subtotal, taxRate, taxAmount, total, currency, language, terms, dueDate, notes, createdBy, issuedAt }) {
  const period = billingPeriod(orders);
  const params = {
    p_tenant_id: tenantId, p_customer_id: company.id || null, p_customer_name: companyName(company), p_customer_tax_id: company.tax_id || null,
    p_order_ids: orders.map((o) => o.id), p_period_start: period ? dayStr(period.start) : null, p_period_end: period ? dayStr(period.end) : null,
    p_subtotal: subtotal, p_tax_rate: taxRate, p_tax_amount: taxAmount, p_total: total, p_currency: currency || "USD", p_language: language, p_payment_terms: terms,
    p_due_date: dueDate ? dayStr(dueDate) : null, p_notes: notes || null, p_created_by: createdBy || null, p_issued_at: issuedAt.toISOString(),
  };
  const { data, error } = await supabase.rpc("create_invoice", params);
  if (error) throw error;
  const row = Array.isArray(data) ? data[0] : data;
  if (!row) throw new Error("create_invoice no devolvió ninguna fila");
  return row;
}

